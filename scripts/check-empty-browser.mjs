import {setSource} from './browser-controls.mjs'
import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
const errors = []
page.on('pageerror', error => errors.push(error.message))
const url = process.env.NETWATCH_URL || 'http://127.0.0.1:4173'
const stored = () => page.evaluate(() => JSON.parse(localStorage.getItem('netwatch-topology-v1')))
try {
  await page.goto(url)
  await page.getByText('Your network starts here', { exact: true }).waitFor()
  assert.equal(await page.locator('.react-flow__node').count(), 0)
  assert.deepEqual(await stored(), { schemaVersion: 1, nodes: [], edges: [] })
  assert.equal(await page.getByRole('button', { name: /sample|preview/i }).count(), 0)
  await page.screenshot({ path: 'docs/screenshots/empty-start-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.screenshot({ path: 'docs/screenshots/empty-start-narrow.png' })
  await page.getByRole('button', { name: 'Create your map' }).click()
  assert.equal(await page.locator('.react-flow__node').count(), 0)
  await page.getByRole('button', { name: 'Add device', exact: true }).click()
  await page.getByLabel('Device name (required)', { exact: true }).fill('Operator device')
  await page.getByLabel('IP address', { exact: true }).fill('203.0.113.9')
  await page.getByRole('dialog').getByRole('button', { name: 'Add device', exact: true }).click()
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes.length === 1)
  const saved = await stored()
  await page.reload()
  await page.getByRole('heading', { name: 'Edit your map', exact: true }).waitFor()
  await page.getByRole('link', { name: 'Network dashboard', exact: true }).click()
  await setSource(page,'browser')
  await page.locator('.health-node').waitFor()
  assert.deepEqual(await stored(), saved)
  await page.getByRole('link', { name: 'Devices', exact: true }).click()
  await page.getByRole('button', { name: 'View details for Operator device' }).click()
  assert.match(await page.getByRole('dialog').innerText(), /Not monitored/)
  await page.keyboard.press('Escape')
  assert.deepEqual(await stored(), saved)
  assert.deepEqual(errors, [])
  console.log('PASS: empty fresh dashboard/editor, no demo controls, desktop/narrow layout, user-created device survives reload and inspection')
} finally { await browser.close() }
