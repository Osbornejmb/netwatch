import { createEditorNetwork } from '../tests/fixtures/editor-network.js'
import { fileURLToPath } from 'node:url'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
import assert from 'node:assert/strict'
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || undefined,args:['--no-sandbox']})
const context=await browser.newContext({viewport:{width:1440,height:1000}})
await context.addInitScript(network => { if (!localStorage.getItem('netwatch-topology-v1')) localStorage.setItem('netwatch-topology-v1', JSON.stringify(network)) }, createEditorNetwork())
const page=await context.newPage()
page.setDefaultTimeout(10000)
const errors=[]
page.on('pageerror',e=>errors.push(e.message))
await page.goto(process.env.NETWATCH_URL || 'http://127.0.0.1:4173')
await page.getByRole('link',{name:'Topology builder',exact:true}).click()
const snapshot=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')))
const original=await snapshot()
await page.getByLabel('Selected device',{exact:true}).selectOption('r1')
const edit=page.getByRole('button',{name:'Edit selected device',exact:true})
await edit.focus(); await page.keyboard.press('Enter')
const dialog=page.getByRole('dialog',{name:'Edit network device'})
assert.ok(await dialog.isVisible())
assert.equal(await page.locator('#device-name').evaluate(e=>e===document.activeElement),true)
await page.getByLabel('Device name (required)',{exact:true}).fill('Updated router')
await page.getByLabel('Management IP address',{exact:true}).fill('192.168.1.2')
await dialog.getByRole('button',{name:'Save changes'}).click()
assert.match(await page.locator('#ip-error').innerText(),/already assigned/)
await page.getByLabel('Management IP address',{exact:true}).fill('host.example')
await dialog.getByRole('button',{name:'Save changes'}).click()
assert.match(await page.locator('#ip-error').innerText(),/IPv4 or IPv6/)
await page.getByLabel('Management IP address',{exact:true}).fill('2001:0DB8:0:0:0:0:0:1')
await page.getByLabel('Description (optional)',{exact:true}).fill('Updated rack')
// Native showModal keeps keyboard focus inside and makes the background inert.
for(let i=0;i<15;i++){
 await page.keyboard.press('Tab')
 assert.ok(await dialog.evaluate(d=>d.contains(document.activeElement)))
}
await dialog.getByRole('button',{name:'Save changes'}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes[0].data.label==='Updated router')
const changed=await snapshot()
assert.equal(changed.nodes[0].id,original.nodes[0].id)
assert.deepEqual(changed.nodes[0].position,original.nodes[0].position)
assert.deepEqual(changed.edges,original.edges)
assert.equal(changed.nodes[0].data.ip,'2001:db8::1')
assert.equal(await edit.evaluate(e=>e===document.activeElement),true)
await edit.click()
await page.getByLabel('Device name (required)',{exact:true}).fill('Cancelled change')
await page.keyboard.press('Escape')
assert.equal(await edit.evaluate(e=>e===document.activeElement),true)
assert.equal((await snapshot()).nodes[0].data.label,'Updated router')
await edit.click()
await page.getByLabel('Device name (required)',{exact:true}).fill('Cancelled too')
await page.getByRole('button',{name:'Cancel',exact:true}).click()
assert.equal((await snapshot()).nodes[0].data.label,'Updated router')
await page.getByRole('button',{name:'Add device',exact:true}).click()
await page.getByLabel('Device name (required)',{exact:true}).fill('IPv6 duplicate')
await page.getByLabel('Management IP address',{exact:true}).fill('2001:db8::1')
await page.getByRole('dialog').getByRole('button',{name:'Add device',exact:true}).click()
assert.match(await page.locator('#ip-error').innerText(),/already assigned/)
await page.getByLabel('Management IP address',{exact:true}).fill('')
await page.getByRole('dialog').getByRole('button',{name:'Add device',exact:true}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes.length===6)
const added=(await snapshot()).nodes.at(-1)
assert.equal(added.data.ip,'')
await page.getByLabel('X position',{exact:true}).fill('123')
await page.getByLabel('Y position',{exact:true}).fill('456')
await page.getByRole('button',{name:'Apply position'}).focus()
await page.keyboard.press('Enter')
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes[0].position.x===123)
assert.deepEqual((await snapshot()).nodes[0].position,{x:123,y:456})
await page.getByLabel('Link source',{exact:true}).selectOption('r1')
await page.getByLabel('Link target',{exact:true}).selectOption(added.id)
await page.getByRole('button',{name:'Add link',exact:true}).focus(); await page.keyboard.press('Enter')
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).edges.length===5)
await page.getByRole('button',{name:'Remove link Updated router to IPv6 duplicate',exact:true}).focus(); await page.keyboard.press('Enter')
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).edges.length===4)
await page.getByLabel('Link target',{exact:true}).selectOption('r1')
await page.getByRole('button',{name:'Add link',exact:true}).click()
assert.match(await page.getByRole('alert').innerText(),/different devices/)
// Invalid and cancelled import retain the edited inventory.
const beforeImport=await snapshot()
await page.locator('input[type=file]').setInputFiles({name:'valid.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify({nodes:[],edges:[]}))})
await page.getByRole('dialog',{name:'Import this map?'}).getByRole('button',{name:'Cancel',exact:true}).click()
assert.deepEqual(await snapshot(),beforeImport)
const invalid=structuredClone(beforeImport); invalid.nodes[1].data.ip='2001:0DB8::1'
await page.locator('input[type=file]').setInputFiles({name:'duplicate.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))})
await page.getByRole('alert').filter({hasText:'Import failed'}).waitFor()
assert.deepEqual(await snapshot(),beforeImport)
await page.getByLabel('Selected device',{exact:true}).selectOption(added.id)
await page.getByLabel('Link target',{exact:true}).selectOption(added.id)
await page.getByRole('button',{name:'Add link',exact:true}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).edges.length===5)
await page.getByRole('button',{name:'Delete selected device'}).focus(); await page.keyboard.press('Enter')
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes.length===5)
assert.ok((await snapshot()).edges.every(e=>e.source!==added.id&&e.target!==added.id))
await page.screenshot({path:fileURLToPath(new URL('../docs/screenshots/inventory-desktop.jpg', import.meta.url)),fullPage:true})
await page.setViewportSize({width:390,height:844})
await page.getByLabel('Selected device',{exact:true}).selectOption('r1')
await edit.click()
assert.ok(await page.getByRole('dialog').isVisible())
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
await page.screenshot({path:fileURLToPath(new URL('../docs/screenshots/inventory-narrow.jpg', import.meta.url)),fullPage:true})
await page.getByRole('button',{name:'Close device dialog'}).focus()
await page.keyboard.press('Shift+Tab')
assert.equal(await page.getByRole('button',{name:'Save changes'}).evaluate(e=>e===document.activeElement),true)
await page.getByLabel('Description (optional)',{exact:true}).fill('Narrow layout edit')
await page.getByRole('button',{name:'Save changes'}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes[0].data.description==='Narrow layout edit')
await page.getByLabel('X position',{exact:true}).fill('234')
await page.getByRole('button',{name:'Apply position'}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes[0].position.x===234)
await page.getByLabel('Link target',{exact:true}).selectOption('r2')
await page.getByRole('button',{name:'Add link',exact:true}).click()
await page.waitForFunction(()=>JSON.parse(localStorage.getItem('netwatch-topology-v1')).edges.length===5)
await page.getByLabel('Selected device',{exact:true}).selectOption('r2')
await page.getByRole('button',{name:'Delete selected device'}).click()
await page.waitForFunction(()=>!JSON.parse(localStorage.getItem('netwatch-topology-v1')).nodes.some(n=>n.id==='r2'))
assert.ok((await snapshot()).edges.every(e=>e.source!=='r2'&&e.target!=='r2'))
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
assert.deepEqual(errors,[])
console.log('PASS: edit preserves IDs/positions/links; malformed/duplicate IP errors; IPv6 normalization; empty address; focus trap/Escape/return; cancel; keyboard move/link add/remove/delete cleanup; rejected/cancelled imports; desktop/narrow')
await browser.close()
