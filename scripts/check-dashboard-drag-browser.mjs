const separated = async () => {
  const boxes = await page.locator('.react-flow__node:visible').evaluateAll(nodes => nodes.map(node => node.getBoundingClientRect().toJSON()))
  for (let a = 0; a < boxes.length; a++) for (let b = a + 1; b < boxes.length; b++) assert.ok(boxes[a].right <= boxes[b].left + 0.5 || boxes[b].right <= boxes[a].left + 0.5 || boxes[a].bottom <= boxes[b].top + 0.5 || boxes[b].bottom <= boxes[a].top + 0.5, 'Cards overlap')
}
const snapDrag = async (id, pixels) => {
  const before = await positions()
  const box = await page.locator(`.react-flow__node[data-id="${id}"]`).boundingBox()
  const start = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  await page.mouse.move(start.x, start.y); await page.mouse.down()
  await page.mouse.move(start.x + pixels, start.y, { steps: 10 })
  await page.waitForFunction(({ id, transform }) => document.querySelector(`.react-flow__node[data-id="${id}"]`).style.transform !== transform, { id, transform: before[id] })
  const during = await positions()
  const xy = transform => transform.match(/translate\(([-\d.]+)px,\s*([-\d.]+)px\)/).slice(1).map(Number)
  const a = xy(before[id]), b = xy(during[id])
  assert.ok(Math.hypot(a[0] - b[0], a[1] - b[1]) <= 64.01, 'Drag exceeded the tether')
  await separated()
  await page.mouse.up()
  await page.waitForFunction(before => Object.entries(before).every(([id, transform]) => document.querySelector(`.react-flow__node[data-id="${id}"]`)?.style.transform === transform), before)
  assert.equal(await page.getByRole('dialog').count(), 0, 'Drag release opened details')
  await separated()
}
