async function fitView(){
 // Let ResizeObserver consume a viewport resize before requesting a new fit.
 await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))))
 await page.locator('.react-flow__controls-fitview').click()
 await page.waitForFunction(()=>{
  const box=document.querySelector('.health-map').getBoundingClientRect()
  return [...document.querySelectorAll('.react-flow__node')].every(node=>{const rect=node.getBoundingClientRect();return rect.left>=box.left-1&&rect.right<=box.right+1&&rect.top>=box.top-1&&rect.bottom<=box.bottom+1})
 })
}
async function drag(id,dx,dy,expectedPeers,expectedLinks){
 const node=page.locator(`.react-flow__node[data-id="${id}"]`)
 const before=await transforms()
 const box=await node.boundingBox()
 const start={x:box.x+box.width/2,y:box.y+box.height/2}
 const incidentBefore=await page.locator('.react-flow__edge-path').evaluateAll(paths=>paths.map(path=>path.getAttribute('d')))
 await page.mouse.move(start.x,start.y);await page.mouse.down();await page.mouse.move(start.x+dx/2,start.y+dy/2,{steps:7})
 assert.equal(await page.getByRole('dialog').count(),0,'Dragging must not open a modal')
 assert.equal(await page.locator('.health-node-connected').count(),expectedPeers)
 assert.equal(await page.locator('.health-path-highlighted').count(),expectedLinks)
 await page.waitForFunction(({id,position})=>document.querySelector(`.react-flow__node[data-id="${id}"]`)?.style.transform!==position,{id,position:before[id]})
 const during=await transforms()
 assert.notEqual(during[id],before[id])
 for(const [other,position] of Object.entries(before))if(other!==id)assert.equal(during[other],position,'Only the dragged node moves')
 await page.waitForFunction(before=>JSON.stringify([...document.querySelectorAll('.react-flow__edge-path')].map(path=>path.getAttribute('d')))!==JSON.stringify(before),incidentBefore)
 await page.mouse.move(start.x+dx,start.y+dy,{steps:7});await page.mouse.up()
 assert.equal(await page.getByRole('dialog').count(),0,'Drag release must not act like a click')
 assert.equal(await page.locator('.health-node-connected').count(),expectedPeers)
 const after=await transforms();assert.notEqual(after[id],before[id])
 return {before,after}
}
