const drag = async (id, distance, keep, blur = false) => {
  const before = await positions()
  const node = page.locator(`.react-flow__node[data-id="${id}"]`)
  let box, zoom, direction
  for (let attempt = 0; attempt < 5; attempt++) {
    box = await node.boundingBox()
    zoom = await page.locator('.react-flow__viewport').evaluate(el => new DOMMatrixReadOnly(getComputedStyle(el).transform).a)
    direction = box.x + box.width / 2 < page.viewportSize().width / 2 ? 1 : -1
    const end = box.x + box.width / 2 + direction * distance * zoom
    if (end >= 10 && end <= page.viewportSize().width - 10) break
    await page.locator('.react-flow__controls-zoomout').click()
    await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))))
  }
  const start = { x: box.x + box.width / 2, y: box.y + box.height / 2 }
  await page.mouse.move(start.x, start.y); await page.mouse.down()
  await page.mouse.move(start.x + direction * distance * zoom, start.y, { steps: 12 })
  await page.waitForFunction(({ id, transform }) => document.querySelector(`.react-flow__node[data-id="${id}"]`).style.transform !== transform, { id, transform: before[id] })
  await separated()
  if (blur) await page.evaluate(() => window.dispatchEvent(new Event('blur')))
  await page.mouse.up()
  if (keep) assert.notEqual((await positions())[id], before[id], 'Valid movement must remain after release')
  else {
    await page.waitForFunction(before => Object.entries(before).every(([id, transform]) => document.querySelector(`.react-flow__node[data-id="${id}"]`)?.style.transform === transform), before)
    assert.deepEqual(await positions(), before, 'An overstretched connection must restore the last valid positions')
  }
  assert.equal(await page.getByRole('dialog').count(), 0)
  await separated()
  return positions()
}
